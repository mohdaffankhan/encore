#!/bin/sh
# Writes the Flathub manifest for a PUBLISHED release: the Flatpak manifest
# (linux/packaging/flatpak/), with Encore's tarball downloaded from that
# GitHub release (and its checksum) instead of a file next to it, as
# Flathub builds everything from sources it downloads itself.
# Output: linux/packaging/flathub/io.github.mohdaffankhan.Encore.yml, to put
# in the Flathub repository (see linux/packaging/flathub/README.md).
# Usage: sh tool/flathub_update.sh 0.2.0
set -eu
version=$1
repo=$(cd "$(dirname "$0")/.." && pwd)
id=io.github.mohdaffankhan.Encore
url=https://github.com/mohdaffankhan/encore/releases/download/v$version/encore-linux-x64.tar.gz

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
gh release download "v$version" -p encore-linux-x64.tar.gz -D "$tmp"
sum=$(sha256sum "$tmp/encore-linux-x64.tar.gz" | cut -d' ' -f1)

src=$repo/linux/packaging/flatpak/$id.yml
out=$repo/linux/packaging/flathub/$id.yml
mkdir -p "$(dirname "$out")"
grep -q '^        path: encore-linux-x64.tar.gz$' "$src" ||
  { echo "the tarball source in $src has changed: update this script" >&2; exit 1; }
{
  echo "# Generated by tool/flathub_update.sh $version from"
  echo "# linux/packaging/flatpak/$id.yml: edit that, then run this again."
  grep -v '^#' "$src" | sed \
    -e "s|^        path: encore-linux-x64.tar.gz\$|        url: $url\\
        sha256: $sum|"
} > "$out"
echo "wrote $out (v$version, $sum)"
